#!/usr/bin/env python3
"""Regression checks for the opt-in guest scalar force-inline mode."""

from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parent.parent
CPU_H = ROOT / "runtime" / "cpu.h"
MAKEFILE = ROOT / "Makefile"

SCALAR_HELPERS = (
    "adds64", "subs64", "adds32", "subs32", "logic64", "logic32",
    "clz64", "clz32", "cls64", "cls32", "rbit64", "rbit32",
    "rev16_32", "rev16_64", "rev32_64",
    "udiv64", "udiv32", "sdiv64", "sdiv32",
)

NOT_FORCED = (
    "rt_dispatch_cached",
    "ldxp_pair32", "stxp_pair32", "ldxp_pair64", "stxp_pair64",
    "casp_pair32", "casp_pair64",
)


class GuestForceInlineTests(unittest.TestCase):
    def test_build_toggle_is_opt_in(self):
        make = MAKEFILE.read_text()
        self.assertIn("GUEST_FORCE_INLINE ?= 0", make)
        self.assertIn("GENFLAGS += -DLARECOMP_GUEST_FORCE_INLINE=1", make)

    def test_scalar_helpers_use_force_inline_macro(self):
        text = CPU_H.read_text()
        self.assertIn("#define GUEST_ALWAYS_INLINE static __inline__ __attribute__((always_inline))", text)
        for name in SCALAR_HELPERS:
            self.assertRegex(text, rf"GUEST_ALWAYS_INLINE\s+[^;{{]+\b{re.escape(name)}\s*\(")

        # ADC/SBC helpers are generated by a macro; all four variants must use
        # the force-inline marker at the definition site.
        for stem in ("adc##N", "sbc##N", "adcs##N", "sbcs##N"):
            self.assertIn(f"GUEST_ALWAYS_INLINE uint##N##_t {stem}", text)

    def test_atomics_and_dispatch_remain_normal_inline(self):
        text = CPU_H.read_text()
        for name in NOT_FORCED:
            self.assertNotRegex(text, rf"GUEST_ALWAYS_INLINE\s+[^;{{]+\b{re.escape(name)}\s*\(")

    def test_clang_honors_force_inline_at_o1(self):
        clang = shutil.which("clang")
        if not clang:
            self.skipTest("clang not available")

        source = r"""
#define LARECOMP_GUEST_FORCE_INLINE 1
#include "cpu.h"

uint64_t probe(Cpu *c, uint64_t a, uint64_t b) {
    uint64_t x = adds64(c, a, b);
    x ^= clz64(x);
    x ^= rev16_64(x);
    return subs64(c, x, b);
}
"""
        with tempfile.TemporaryDirectory() as td:
            td = Path(td)
            src = td / "probe.c"
            ir = td / "probe.ll"
            src.write_text(source)
            result = subprocess.run(
                [clang, "-O1", "-fno-inline-functions", "-S", "-emit-llvm",
                 "-I", str(ROOT / "runtime"), str(src), "-o", str(ir)],
                capture_output=True, text=True,
            )
            self.assertEqual(result.returncode, 0, result.stderr)
            llvm = ir.read_text()
            for name in ("adds64", "clz64", "rev16_64", "subs64"):
                self.assertNotRegex(llvm, rf"call\s+[^@]*@{name}\b")


if __name__ == "__main__":
    unittest.main(verbosity=2)
